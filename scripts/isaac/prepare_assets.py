"""Build everything the Isaac task loads. Needs mujoco + xacro + usd-core, NOT Isaac.

    python scripts/isaac/prepare_assets.py                  # CRX, all three panels
    python scripts/isaac/prepare_assets.py --panels door

Run it on the machine that will run Isaac Sim (the URDF holds absolute mesh paths).
Writes into outputs/isaac/:
    crx10ia_l_paintcell.urdf       rail + CRX + spray gun + nozzle frame
    expert_crx10ia_l_<panel>.npz   scripted-expert joint path + MuJoCo reference metrics
    panel_<panel>.usda             panel mesh with per-vertex paint colours
"""
import argparse
import json
import os
import shutil
import sys
from pathlib import Path

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from paintbot.cell_layout import PANEL_KINDS, make_panel  # noqa: E402
from paintbot.isaac_task.expert import export_expert, load_expert  # noqa: E402
from paintbot.isaac_task.panel_usd import write_panel_usd  # noqa: E402
from paintbot.isaac_task.robot_urdf import build_cell_urdf  # noqa: E402
from paintbot.mujoco_cell import assets  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--robot", default="crx10ia_l")
    ap.add_argument("--panels", nargs="+", default=list(PANEL_KINDS), choices=PANEL_KINDS)
    ap.add_argument("--out", default="outputs/isaac")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    if not assets.available(args.robot):
        print(f"Fetching {args.robot} ...")
        assets.fetch_fanuc(args.robot)
    urdf = build_cell_urdf(args.robot)
    shutil.copy(urdf, out / urdf.name)
    print(f"robot URDF   {out / urdf.name}")

    for kind in args.panels:
        npz = export_expert(kind, args.robot, out=out / f"expert_{args.robot}_{kind}.npz")
        ref = load_expert(npz)["meta"]["mujoco_reference"]
        usd = write_panel_usd(make_panel(kind), out / f"panel_{kind}.usda")
        print(f"{kind:7s} expert {npz.name}  panel {usd.name}  "
              f"MuJoCo coverage {ref['coverage']:.3f}  cv {ref['uniformity_cv']:.3f}")
    (out / "README.txt").write_text(
        "Generated by scripts/isaac/prepare_assets.py; re-run after changing the cell.\n"
        + json.dumps({"robot": args.robot, "panels": args.panels}) + "\n")


if __name__ == "__main__":
    main()
